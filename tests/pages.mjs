import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { browserPath } from '../server/files.mjs';
import mammoth from 'mammoth';
import { PDFParse } from 'pdf-parse';
const browser = await chromium.launch({ headless: true, ...(browserPath() ? { executablePath: browserPath() } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1200 } });
await context.addInitScript(() => { window.print = () => { window.__manmanPrinted = true; }; });
const page = await context.newPage(); const errors = [], failedAssets = [], apiRequests = [], modelRequests = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.url().startsWith('http://127.0.0.1:4319/') && response.status() >= 400) failedAssets.push(response.url()); });
page.on('request', request => { if (new URL(request.url()).pathname.includes('/api/')) apiRequests.push(request.url()); });
const text = '陈小月\n产品运营\n工作经历\n参与策划6场线上活动，累计1200人参加。\n教育背景\n上海大学 | 本科 | 2018—2022';
const output = { summary: '保留已有数据，精简表达。', strengths: ['有实际活动经验'], suggestions: [{ original: '参与策划6场线上活动，累计1200人参加。', replacement: '参与策划6场线上活动，累计吸引1200人参与。', reason: '保留事实与职责范围。', category: '表达', needsConfirmation: false }], questions: [] };
await mkdir('../../work/pages-checks', { recursive: true });
try {
  await page.route('https://model-test.invalid/**', async route => {
    const request = route.request(); modelRequests.push(request);
    assert.equal(request.headers().authorization, 'Bearer pages-test-not-a-real-key');
    const data = request.postDataJSON();
    await route.fulfill({ contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify({ choices: [{ message: { content: data.messages.length === 1 ? 'OK' : JSON.stringify(output) } }] }) });
  });
  await page.goto('http://127.0.0.1:4319/manman-resume/');
  await page.evaluate(() => document.fonts.ready);
  await page.getByRole('heading', { name: '先认识一下你' }).waitFor();
  assert.equal(await page.locator('.brand img').evaluate(el => el.complete && el.naturalWidth > 0), true);
  await page.screenshot({ path: '../慢慢GitHub-Pages预览.png', fullPage: true });
  await page.getByRole('button', { name: '连接我的模型' }).click();
  await page.locator('#provider').selectOption('tokendance');
  assert.equal(await page.locator('#base-url').inputValue(), 'https://tokendance.space/gateway/v1');
  await page.locator('#provider').selectOption('custom');
  await page.locator('#base-url').fill('https://model-test.invalid/v1');
  await page.locator('#model').fill('test-model');
  await page.getByLabel('API Key').fill('pages-test-not-a-real-key');
  await page.getByRole('button', { name: '测试连接' }).click();
  await page.getByText('连接成功，可以开始打磨了').waitFor();
  await page.getByRole('button', { name: '完成设置' }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'resume.txt', mimeType: 'text/plain', buffer: Buffer.from(text) });
  await page.waitForFunction(() => document.querySelector('#resume-text')?.value.includes('陈小月'));
  await page.getByRole('button', { name: '下一步，看清目标' }).click();
  await page.getByRole('button', { name: '开始慢慢打磨' }).click();
  await page.getByRole('heading', { name: '逐条看看，慢慢决定' }).waitFor();
  await page.getByRole('button', { name: '采纳这处修改' }).click();
  await page.getByRole('button', { name: '整理我的简历' }).click();
  const [word] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '下载 Word · DOCX' }).click()]);
  await word.saveAs('../../work/pages-checks/browser-resume.docx');
  const wordBuffer = await readFile('../../work/pages-checks/browser-resume.docx');
  assert.ok((await mammoth.extractRawText({ buffer: wordBuffer })).value.includes('累计吸引1200人参与'));
  const [pop] = await Promise.all([page.waitForEvent('popup'), page.getByRole('button', { name: '打印 / 保存 PDF' }).click()]);
  await pop.waitForFunction(() => window.__manmanPrinted === true);
  assert.ok(await pop.getByText('累计吸引1200人参与。').count());
  const pdf = await pop.pdf({ format: 'A4', preferCSSPageSize: true });
  const parser = new PDFParse({ data: pdf });
  try { assert.ok((await parser.getText()).text.includes('陈小月')); } finally { await parser.destroy(); }
  await pop.close();
  assert.equal(modelRequests.length, 2, 'browser calls the provider directly for test and optimization');
  assert.deepEqual(apiRequests, [], 'static mode never requests a nonexistent backend');
  assert.ok(!(await page.evaluate(() => JSON.stringify(localStorage))).includes('pages-test-not-a-real-key'));
  await page.getByRole('button', { name: '读懂经历 导入你的简历' }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'resume.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: wordBuffer });
  await page.waitForFunction(() => document.querySelector('#resume-text')?.value.includes('累计吸引1200人参与'));
  await page.locator('input[type=file]').setInputFiles({ name: 'resume.pdf', mimeType: 'application/pdf', buffer: pdf });
  await page.waitForFunction(() => document.querySelector('.file-loaded')?.textContent.includes('resume.pdf'));
  assert.ok((await page.locator('#resume-text').inputValue()).includes('陈小月'));
  await page.locator('input[type=file]').setInputFiles({ name: 'old.doc', mimeType: 'application/msword', buffer: Buffer.from('not a real doc') });
  await page.getByRole('alert').filter({ hasText: '网页版请导入 DOCX' }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: '连接我的模型' }).waitFor();
  assert.deepEqual(failedAssets, []);
  assert.deepEqual(errors, []);
  console.log('Pages checks passed: repository base path, local fonts, browser TXT/DOCX/PDF import, direct BYOK, accepted edits, editable Word, printable searchable Chinese PDF, no backend calls and no key persistence.');
} finally { await context.close(); await browser.close(); }
